import { createAsyncThunk, createSlice } from "@reduxjs/toolkit"; // Import helpers for async requests and Redux state.
import { fetchProfile } from "../services/auth"; // Reuse the profile endpoint already defined in the auth service.
import { USER_ID_STORAGE_KEY } from "../services/authSession";

function getStoredUserId() { // Restore the non-secret user ID after a browser refresh.
  try { // Read browser session storage when it is available.
    return sessionStorage.getItem(USER_ID_STORAGE_KEY); // Return the ID saved after login.
  } catch { // Handle browsers or environments where session storage is disabled.
    return null; // Let the app show its missing-user-ID state instead of crashing.
  } // Finish reading the stored ID.
} // Finish the session ID helper.

export const loadProfile = createAsyncThunk( // Create a Redux action that fetches one user's profile.
  "profile/loadProfile", // Give the async action a descriptive Redux action type.
  async (userId, { rejectWithValue }) => { // Receive the user ID and provide expected API errors to Redux.
    try { // Start the API request and handle its possible failure.
      return await fetchProfile(userId); // Request profile data through the existing service function.
    } catch (error) { // Catch network or server errors from Axios.
      return rejectWithValue( // Store a readable error in the rejected Redux action.
        error.response?.data?.message ?? error.message ?? "Unable to load your profile."
      ); // Finish returning the error message.
    } // Finish the request error handler.
  }, // Finish the async thunk callback.
  { // Configure when a request is allowed to start.
    condition: (_userId, { getState }) => getState().profile.status !== "loading", // Prevent duplicate requests while one is already active.
  } // Finish the thunk options.
); // Finish creating the async profile action.

const initialState = { // Define an empty profile; profile values come from the API.
  userId: getStoredUserId(), // Restore the logged-in user's ID so profile requests also work after refresh.
  data: null, // Store the profile response after it loads.
  status: "idle", // Track whether the profile request is idle, loading, successful, or failed.
  error: null, // Store a readable request error when loading fails.
}; // Finish the initial Redux state.

const profileSlice = createSlice({ // Create the profile reducer and its synchronous actions.
  name: "profile", // Name this slice for generated action types and Redux DevTools.
  initialState, // Start with no profile data until the API responds.
  reducers: { // Define synchronous changes to the profile state.
    profileUserIdSet(state, action) { // Save the user ID returned by the login endpoint.
      state.userId = action.payload; // Make the ID available to pages that fetch the profile.
      state.data = null; // Clear any previous user's profile before loading the new one.
      state.status = "idle"; // Reset request status for the newly selected user.
      state.error = null; // Clear errors associated with the previous user.
    }, // Finish the user ID reducer.
    profileSessionCleared(state) {
      state.userId = null;
      state.data = null;
      state.status = "idle";
      state.error = null;
    },
  }, // Finish the synchronous reducer definitions.
  extraReducers: (builder) => { // Handle the lifecycle actions generated by loadProfile.
    builder // Start adding profile request lifecycle handlers.
      .addCase(loadProfile.pending, (state) => { // Handle the beginning of a profile request.
        state.status = "loading"; // Let the page show a loading indicator.
        state.error = null; // Clear any error from a previous attempt.
      }) // Finish the loading handler.
      .addCase(loadProfile.fulfilled, (state, action) => { // Handle a successful profile response.
        state.data = action.payload?.profile ?? action.payload; // Store the profile object returned by the API.
        state.status = "succeeded"; // Mark profile loading as successful.
      }) // Finish the success handler.
      .addCase(loadProfile.rejected, (state, action) => { // Handle a failed profile response.
        state.status = "failed"; // Mark the request as failed so the page can show its error state.
        state.error = action.payload ?? action.error.message; // Keep the readable API error.
      }); // Finish registering request lifecycle handlers.
  }, // Finish async lifecycle reducers.
}); // Finish creating the profile slice.

export const { profileUserIdSet, profileSessionCleared } = profileSlice.actions; // Export authentication state actions.
export default profileSlice.reducer; // Export the reducer so the store can register the profile state.
